"""
Experiment tracking: experiments/registry.csv (source of truth) -> experiments/EXPERIMENTS.md (readable table).

Every run gets an id EXP-NNN. The id goes in the notebook header, the kernel version message and the
Kaggle submission message ("EXP-003 ..."), so leaderboard scores can be matched back automatically.

    # after a training kernel finishes: download its output and register it
    kaggle kernels output hlly34/rsna-knee-train -p runs/EXP-002
    python scripts/track.py add EXP-002 --kernel hlly34/rsna-knee-train --version 3 --outputs runs/EXP-002 \
        --notes "teacher, 5 folds, report labels"
    # pull public LB scores for every submission whose message starts with an EXP id
    python scripts/track.py lb
    # re-render the markdown table only
    python scripts/track.py render
"""
import argparse
import datetime as dt
import glob
import json
import os
import re
import subprocess

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REG = os.path.join(ROOT, "experiments", "registry.csv")
MD = os.path.join(ROOT, "experiments", "EXPERIMENTS.md")
COLS = ["exp_id", "date", "kind", "kernel", "version", "exp_name", "backbone", "img_size", "epochs", "labels",
        "pseudo", "folds", "n_train", "oof_auc", "gold_auc_mean_fold", "gold_auc_ensemble", "lb_public",
        "minutes", "notes"]


def load() -> pd.DataFrame:
    if os.path.exists(REG):
        return pd.read_csv(REG, dtype=str).reindex(columns=COLS)
    return pd.DataFrame(columns=COLS)


def save(df: pd.DataFrame) -> None:
    os.makedirs(os.path.dirname(REG), exist_ok=True)
    df.to_csv(REG, index=False)
    render(df)


def upsert(df: pd.DataFrame, row: dict) -> pd.DataFrame:
    row = {k: ("" if v is None else str(v)) for k, v in row.items() if k in COLS}
    if (df.exp_id == row["exp_id"]).any():
        for k, v in row.items():
            if v != "":
                df.loc[df.exp_id == row["exp_id"], k] = v
        return df
    return pd.concat([df, pd.DataFrame([row])], ignore_index=True)


def cmd_add(a):
    row = {"exp_id": a.exp_id, "date": dt.date.today().isoformat(), "kind": a.kind, "kernel": a.kernel,
           "version": a.version, "notes": a.notes}
    metrics = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(a.outputs or "", "**", "fold*_metrics.json"),
                                                            recursive=True))] if a.outputs else []
    if metrics:
        m0 = metrics[0]
        row.update(exp_name=m0["exp_name"], backbone=m0["backbone"], img_size=m0["img_size"], epochs=m0["epochs"],
                   labels="+".join(os.path.splitext(x)[0] for x in m0["labels"]), pseudo=m0["pseudo"],
                   folds=",".join(str(m["fold"]) for m in metrics), n_train=m0["n_train"],
                   minutes=round(sum(m["minutes"] for m in metrics), 1))
    cvs = glob.glob(os.path.join(a.outputs or "", "**", "*_cv.json"), recursive=True) if a.outputs else []
    if cvs:
        cv = json.load(open(cvs[0]))
        row.update(oof_auc=cv.get("oof_auc", ""), gold_auc_mean_fold=cv.get("gold_auc_mean_fold", ""),
                   gold_auc_ensemble=cv.get("gold_auc_ensemble", ""))
    elif metrics:
        golds = [m["gold_auc"] for m in metrics if "gold_auc" in m]
        row.update(gold_auc_mean_fold=round(sum(golds) / len(golds), 4) if golds else "",
                   oof_auc=metrics[0].get("oof_auc", "") if len(metrics) == 1 else "")
    for kv in a.set or []:
        k, v = kv.split("=", 1)
        row[k] = v
    save(upsert(load(), row))
    print(f"registered {a.exp_id}")


def cmd_lb(a):
    out = subprocess.run(["kaggle", "competitions", "submissions", a.competition, "--format", "json"],
                         capture_output=True, text=True).stdout
    subs = json.loads(out[out.find("["):]) if "[" in out else []
    df = load()
    for s in subs:
        m = re.match(r"(EXP-\d+)", str(s.get("description", "")))
        score = s.get("publicScore") or s.get("public_score")
        if m and score not in (None, "", "None"):
            df = upsert(df, {"exp_id": m.group(1), "lb_public": score})
            print(m.group(1), score, s.get("status"))
    save(df)


def render(df: pd.DataFrame = None) -> None:
    df = load() if df is None else df
    show = ["exp_id", "date", "kind", "exp_name", "backbone", "img_size", "epochs", "labels", "pseudo", "folds",
            "oof_auc", "gold_auc_mean_fold", "gold_auc_ensemble", "lb_public", "minutes", "kernel", "version", "notes"]
    lines = [
        "# Experiment registry",
        "",
        "Generated by `scripts/track.py` from `experiments/registry.csv` — edit the CSV or use the script, not this file.",
        "",
        "* **oof_auc**: macro AUC of out-of-fold predictions vs report-derived targets (all folds pooled). "
        "Noise floor ≈ 0.003.",
        "* **gold_auc_mean_fold / _ensemble**: macro AUC on the 58 radiologist-labelled studies, single fold "
        "average vs rank-averaged fold ensemble. Noise ≈ ±0.02.",
        "* **lb_public**: Kaggle public leaderboard (matched by the `EXP-NNN` prefix of the submission message).",
        "",
        "| " + " | ".join(show) + " |",
        "|" + "---|" * len(show),
    ]
    for _, r in df.fillna("").iterrows():
        lines.append("| " + " | ".join(str(r.get(c, "")).replace("|", "/") for c in show) + " |")
    open(MD, "w").write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("add")
    p.add_argument("exp_id")
    p.add_argument("--kind", default="train", choices=["train", "infer", "cache", "submit"])
    p.add_argument("--kernel", default="")
    p.add_argument("--version", default="")
    p.add_argument("--outputs", default=None, help="downloaded kernel output dir")
    p.add_argument("--notes", default="")
    p.add_argument("--set", nargs="*", help="extra column=value pairs")
    p = sub.add_parser("lb")
    p.add_argument("--competition", default="rsna-knee-abnormality-detection")
    sub.add_parser("render")
    a = ap.parse_args()
    {"add": cmd_add, "lb": cmd_lb, "render": lambda _: render()}[a.cmd](a)


if __name__ == "__main__":
    main()
